#!/usr/bin/env node
// Writes supabase/seed.sql from the canonical project roster.
//
//   npm run db:seed:generate   regenerate supabase/seed.sql
//   npm run db:seed:check      fail if supabase/seed.sql is out of date
//
// The roster in src/lib/mock/projects/roster.ts stays the single source of the
// nine canonical projects; seed.sql is a generated export of it, never edited
// by hand. Only the project record is exported. The simulation parameters
// (scale, healthOffset, seed) are not facts about a client and stay out of the
// database; see src/lib/projects/fixture-analytics.ts.
//
// Requires a Node.js that runs TypeScript directly (22.18+, 23.6+ or 24+):
// roster.ts has type-only imports, so it loads without a build step.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rosterFile = path.join(root, "src/lib/mock/projects/roster.ts");
const seedFile = path.join(root, "supabase/seed.sql");

const { PROJECTS } = await import(pathToFileURL(rosterFile).href);

const sql = (value) => `'${String(value).replace(/'/g, "''")}'`;

function assert(condition, message) {
  if (!condition) {
    console.error(`generate-projects-seed: ${message}`);
    process.exit(1);
  }
}

const columns = [
  "id", "name", "client", "domain", "initials", "industry", "type", "status",
  "goal", "market", "language", "target_location", "summary", "started_on",
  "created_at", "updated_at",
];

const rows = PROJECTS.map((project) => {
  assert(project.domain === project.domain.toLowerCase(), `${project.id}: domain is not canonical`);
  assert(/T00:00:00Z$/.test(project.startedAt), `${project.id}: startedAt is not a midnight-UTC date`);

  // An import keeps a record's history: created_at is when the engagement
  // started, updated_at is its last recorded change.
  const values = [
    project.id, project.name, project.client, project.domain, project.initials,
    project.industry, project.type, project.status, project.goal, project.market,
    project.language, project.targetLocation, project.summary,
    project.startedAt.slice(0, 10), project.startedAt, project.updatedAt,
  ];
  return `  (${values.map(sql).join(", ")})`;
});

const output = `-- GENERATED by scripts/generate-projects-seed.mjs from
-- src/lib/mock/projects/roster.ts. Do not edit; run \`npm run db:seed:generate\`.
--
-- The ${PROJECTS.length} canonical projects. Safe to run repeatedly: a project whose id
-- already exists is left exactly as it is, so a re-run neither duplicates rows
-- nor overwrites changes made since.

insert into public.projects (
  ${columns.join(", ")}
)
values
${rows.join(",\n")}
on conflict (id) do nothing;
`;

if (process.argv.includes("--check")) {
  const current = existsSync(seedFile) ? readFileSync(seedFile, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== output) {
    console.error("supabase/seed.sql is out of date with the project roster. Run `npm run db:seed:generate`.");
    process.exit(1);
  }
  console.log(`supabase/seed.sql is up to date (${PROJECTS.length} projects).`);
} else {
  writeFileSync(seedFile, output);
  console.log(`Wrote supabase/seed.sql (${PROJECTS.length} projects).`);
}
